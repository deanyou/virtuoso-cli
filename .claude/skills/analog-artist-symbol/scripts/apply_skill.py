#!/usr/bin/env python3
"""Apply a generated SKILL script through vcli skill.eval."""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("il", help="SKILL script generated by svg2oa.py")
    ap.add_argument("--dry-run", action="store_true",
                    help="print the RPC params JSON without invoking vcli")
    ap.add_argument("--cwd", help="working directory for the vcli invocation")
    args = ap.parse_args()

    code = Path(args.il).read_text(encoding="utf-8")
    params = {"code": code}
    if args.dry_run:
        print(json.dumps(params, ensure_ascii=False))
        return 0

    if os.environ.get("VCLI_CAPABILITY") != "admin":
        print("warning: skill.eval usually requires VCLI_CAPABILITY=admin",
              file=sys.stderr)
    cmd = ["vcli", "rpc", "call", "--method", "skill.eval",
           "--params", json.dumps(params)]
    proc = subprocess.run(cmd, cwd=args.cwd, text=True, capture_output=True)
    sys.stdout.write(proc.stdout)
    sys.stderr.write(proc.stderr)
    return proc.returncode


if __name__ == "__main__":
    sys.exit(main())
